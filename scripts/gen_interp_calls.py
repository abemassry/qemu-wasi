#!/usr/bin/env python3
"""
Generate tcg/wasm32/wasi-interp-calls.c.inc: the helper-call dispatcher for
the wasm TB interpreter (tcg/wasm32/wasi-interp.c.inc).

A TB calls QEMU helpers with call_indirect, and wasm checks the callee's
exact signature at every indirect call. A C function pointer call compiles
to call_indirect with the pointer's prototype, so the interpreter needs one
correctly typed call per signature shape. Parameters and results are i32 or
i64 (Int128 values travel by pointer), so a shape is fully described by the
result kind, the parameter count and which parameters are i64.

Usage: scripts/gen_interp_calls.py > qemu-src/tcg/wasm32/wasi-interp-calls.c.inc
"""

MAX_PARAMS = 8
RESULTS = [("void", None), ("I", "uint32_t"), ("L", "uint64_t")]


def sig_id(r, n, mask):
    return r * ((1 << (MAX_PARAMS + 1)) - 1) + ((1 << n) - 1) + mask


def main():
    out = []
    w = out.append
    w("/*")
    w(" * Helper-call dispatch for the wasm TB interpreter (wasi-interp.c.inc).")
    w(" * Generated by scripts/gen_interp_calls.py -- do not edit.")
    w(" *")
    w(" * INTERP_SIG(r, n, m): result r (0 none, 1 i32, 2 i64), n parameters,")
    w(" * bit i of m set when parameter i is i64 rather than i32.")
    w(" */")
    w("")
    w(f"#define INTERP_MAX_PARAMS {MAX_PARAMS}")
    w(f"#define INTERP_SIG(r, n, m) \\")
    w(f"    ((r) * {(1 << (MAX_PARAMS + 1)) - 1} + ((1u << (n)) - 1) + (m))")
    w("")
    w("static uint64_t interp_call_helper(uint32_t sig, uint32_t fn,")
    w("                                   const uint64_t *a)")
    w("{")
    w("    typedef uint32_t I;")
    w("    typedef uint64_t L;")
    w("")
    w("    switch (sig) {")
    for r, (rname, rtype) in enumerate(RESULTS):
        for n in range(MAX_PARAMS + 1):
            for mask in range(1 << n):
                ptypes = ["L" if mask >> i & 1 else "I" for i in range(n)]
                proto = ", ".join(ptypes) if ptypes else "void"
                args = ", ".join(f"({t})a[{i}]" for i, t in enumerate(ptypes))
                fp = f"(({rname} (*)({proto}))(uintptr_t)fn)"
                sid = sig_id(r, n, mask)
                if rtype is None:
                    w(f"    case {sid}: {fp}({args}); return 0;")
                else:
                    w(f"    case {sid}: return {fp}({args});")
    w("    default:")
    w("        g_assert_not_reached();")
    w("    }")
    w("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
